"""Rendering a research report as Markdown for export."""

from __future__ import annotations

import re
from typing import Any

STATUS_LABELS = {
    "complete": "Complete — every sub-question has supporting evidence",
    "partial": "Partial — some sub-questions lack strong evidence",
    "failed": "No answer — the sources did not contain relevant evidence",
}
SECTION_LABELS = {
    "answered": "Answered",
    "weak": "Thin evidence",
    "not_found": "No evidence found",
    "skipped": "Not researched (limit reached)",
}


def _md_escape(text: str) -> str:
    """Neutralise Markdown/HTML syntax in source-derived text so exports render as plain text."""
    text = text.replace("\\", "\\\\")
    text = re.sub(r"([`*_\[\]<>#|])", r"\\\1", text)
    return text.replace("\n", " ")


def to_markdown(report: dict[str, Any]) -> str:
    lines: list[str] = [f"# {_md_escape(report['question'])}", ""]
    mode = (
        "AI-written, citation-checked" + (f" ({report['model']})" if report.get("model") else "")
        if report["mode"] == "llm"
        else "Extractive (quoted from sources)"
    )
    lines += [f"**Status:** {STATUS_LABELS.get(report['status'], report['status'])}  ", f"**Mode:** {mode}", ""]

    for section in report["sections"]:
        lines += [f"## {_md_escape(section['question'])}", "", f"*{SECTION_LABELS.get(section['status'], section['status'])}*", ""]
        if section["sentences"]:
            for sentence in section["sentences"]:
                refs = "".join(f"[{n}]" for n in sentence["citations"])
                flag = " *(weak support)*" if sentence["support"] == "weak" else ""
                lines.append(f"- {_md_escape(sentence['text'])} {refs}{flag}")
        else:
            lines.append("- No supporting evidence was found in the selected sources.")
        lines.append("")

    if report["conflicts"]:
        lines += ["## Conflicting figures", ""]
        for c in report["conflicts"]:
            lines.append(
                f"- **{_md_escape(c['summary'])}** — “{_md_escape(c['a']['sentence'])}” [{c['a']['citation']}] vs “{_md_escape(c['b']['sentence'])}” [{c['b']['citation']}]"
            )
        lines.append("")

    if report.get("removed_claims"):
        lines += ["## Claims removed by verification", ""]
        for claim in report["removed_claims"]:
            lines.append(f"- ~~{_md_escape(claim['text'])}~~ — {claim['reason']}")
        lines.append("")

    lines += ["## Limitations", ""] + [f"- {_md_escape(item)}" for item in report["limitations"]] + [""]

    lines += ["## Sources cited", ""]
    for cite in report["citations"]:
        page = f", page {cite['page']}" if cite.get("page") else ""
        lines.append(f"{cite['id']}. **{_md_escape(cite['source_title'])}**{page} — “{_md_escape(cite['quote'])}”")
    lines.append("")

    stats = report["stats"]
    lines += [
        "## How this report was made",
        "",
        f"Sourcebound searched {stats['passages_in_scope']} passages in {stats['sources_in_scope']} source(s) "
        f"using {stats['tool_calls']} tool call(s) and {stats['llm_calls']} model call(s) in {stats['duration_ms'] / 1000:.1f}s.",
        "",
    ]
    for event in report["trace"]:
        lines.append(f"{event['step']}. **{_md_escape(event['title'])}** — {_md_escape(event['detail'])}")
    lines += ["", "_Generated by Sourcebound. Verify important facts against the original sources._", ""]
    return "\n".join(lines)
